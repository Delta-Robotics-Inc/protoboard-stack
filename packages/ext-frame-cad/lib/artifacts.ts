/**
 * The files the build123d generators write, as UHD artifacts
 * (`@protoboardai/ext-frame-cad/artifacts`). A module's source declares them
 * with UHD's pure helpers (`withGeometry`, `feature`, `own`, `procedural`);
 * the layout itself is this extension's knowledge, so it lives here, not in
 * UHD (PB-801).
 *
 * The common layout, per generated body:
 *   <name>.step            body with each interface as a named sub-shape (D1)
 *   <name>.glb             the same, tessellated, for viewers
 *   <name>.manifest.json   feature name -> signature (area, centroid, normal)
 *   interfaces/<id>.glb    one artifact per interface (D2)
 * and nothing for D3 (procedural), which viewers derive from parameters.
 *
 * Plate modules use the `cad` capability's layout instead (PB-822,
 * tool-integrations §4): the same bodies as standard outputs in
 * `<dir>/out/` (body.step, body.glb, body.manifest.json, body.dxf,
 * interfaces/<id>.glb) and the native design in `<dir>/frame-cad/`.
 */
import type { ArtifactDef } from "@deltarobotics/uhd";

export const FRAME_CAD_GENERATOR = "@protoboardai/ext-frame-cad py/frame_cad.py";
export const HARDWARE_CAD_GENERATOR = "@protoboardai/ext-frame-cad py/hardware_cad.py";

export interface CadOptions {
  /** Project-relative directory holding the generated files. */
  dir: string;
  /** Base name of the generated body files. */
  name: string;
  /**
   * The generator: a project-relative script (recorded as the source artifact's
   * file), or a package-qualified name such as FRAME_CAD_GENERATOR (recorded
   * as provenance only, with `generatorNote`).
   */
  generator: string;
  tool: string;
  /** Interfaces that have a per-interface artifact (D2). */
  interfaces?: string[];
  /** Extra id prefix when a module has several bodies (e.g. "camera"). */
  prefix?: string;
  /** Description of a generator that is not a project file (it ships in a package). */
  generatorNote?: string;
}

const inPackage = (generator: string) => generator.startsWith("@") || generator.includes(" ");

/** Body file paths of one generated body. */
interface BodyFiles {
  step: string;
  glb: string;
  manifest: string;
  iface: (id: string) => string;
}

/** Source, STEP body, GLB body, manifest and per-interface GLBs for one generated body. */
export function cadArtifacts(o: CadOptions): ArtifactDef[] {
  return bodyArtifacts(o, { step: `${o.dir}/${o.name}.step`, glb: `${o.dir}/${o.name}.glb`, manifest: `${o.dir}/${o.name}.manifest.json`, iface: (id) => `${o.dir}/interfaces/${id}.glb` });
}

function bodyArtifacts(o: Omit<CadOptions, "dir">, f: BodyFiles): ArtifactDef[] {
  const p = o.prefix ? `${o.prefix}_` : "";
  const provenance = { generatedFrom: `cad_${p}source`, tool: o.tool };
  const packaged = inPackage(o.generator);
  return [
    {
      id: `cad_${p}source`,
      name: `${o.name} generator`,
      type: "cad",
      role: "source",
      format: o.generator.split(".").pop(),
      ...(packaged ? { description: o.generatorNote ?? `Generated by ${o.generator}.` } : { filePath: o.generator }),
    },
    {
      id: `cad_${p}step`,
      name: `${o.name} (STEP)`,
      type: "3d_model",
      role: "body",
      format: "step",
      units: "mm",
      filePath: f.step,
      provenance,
      description: "Body plus one named sub-shape per interface feature; features and signatures in the manifest.",
    },
    {
      id: `cad_${p}glb`,
      name: `${o.name} (GLB)`,
      type: "3d_model",
      role: "body",
      format: "glb",
      units: "m",
      filePath: f.glb,
      provenance: { ...provenance, generatedFrom: `cad_${p}step` },
      description: "Viewer mesh of the STEP body (glTF metres, Y-up).",
    },
    {
      id: `cad_${p}manifest`,
      name: `${o.name} feature manifest`,
      type: "cad",
      role: "source",
      format: "json",
      filePath: f.manifest,
      provenance: { ...provenance, generatedFrom: `cad_${p}step` },
    },
    ...(o.interfaces ?? []).map(
      (id): ArtifactDef => ({
        id: `cad_if_${id}`,
        name: `${id} geometry`,
        type: "3d_model",
        role: "interface",
        interfaceId: id,
        format: "glb",
        units: "m",
        filePath: f.iface(id),
        provenance: { ...provenance, generatedFrom: `cad_${p}step` },
      }),
    ),
  ];
}

/** The native folder of this provider in a module's provider directory (`native` in the manifest). */
export const FRAME_CAD_NATIVE = "frame-cad";

/**
 * Everything the `cad` capability writes for a plate module whose
 * `cad.config.ts` is in `dir` (`protoboard run cad:generate` and
 * `cad:export`, or the `frame-cad` alias): the standard outputs in
 * `<dir>/out/` (body, manifest, per-interface GLBs, the cutting DXF) and the
 * native design in `<dir>/frame-cad/` (the parameters the generator ran on
 * and the frames it generated).
 */
export function plateCadArtifacts(o: { dir: string; name: string; interfaces: string[]; tool?: string }): ArtifactDef[] {
  const tool = o.tool ?? "build123d 0.13.0";
  const out = `${o.dir}/out`;
  const native = `${o.dir}/${FRAME_CAD_NATIVE}`;
  return [
    ...bodyArtifacts(
      {
        name: o.name,
        generator: FRAME_CAD_GENERATOR,
        tool,
        interfaces: o.interfaces,
        generatorNote: `Generated by ${FRAME_CAD_GENERATOR} from ${native}/params.json (protoboard run cad:generate, then cad:export).`,
      },
      { step: `${out}/body.step`, glb: `${out}/body.glb`, manifest: `${out}/body.manifest.json`, iface: (id) => `${out}/interfaces/${id}.glb` },
    ),
    { id: "cad_params", name: `${o.name} generator parameters`, type: "cad", role: "source", format: "json", filePath: `${native}/params.json`, description: "Bolt patterns, frames and design values read from this module's interfaces and its cad.config.ts constraints." },
    { id: "cad_frames", name: `${o.name} generated frames`, type: "cad", role: "source", format: "json", filePath: `${native}/frames.json`, provenance: { generatedFrom: "cad_source", tool } },
    {
      id: "cad_dxf",
      name: `${o.name} (DXF)`,
      type: "cad",
      role: "drawing",
      format: "dxf",
      units: "mm",
      filePath: `${out}/body.dxf`,
      provenance: { generatedFrom: "cad_step", tool },
      description: "Manufacturing profiles for CNC routing: the plate outline with every hole (layer plate) and any side-clamp plates (layer clamp_<interface>).",
    },
  ];
}

/**
 * Everything the `cad` capability writes for a fastener module (screw, nut,
 * spacer, standoff) whose `cad.config.ts` is in `dir` (`protoboard run
 * cad:generate` and `cad:export`, or the `hardware-cad` alias): its nominal
 * body as standard outputs in `<dir>/out/` and the parameters it was built
 * from in `<dir>/frame-cad/params.json`.
 */
export function hardwareCadArtifacts(o: { dir: string; name: string; tool?: string }): ArtifactDef[] {
  const tool = o.tool ?? "build123d 0.13.0";
  const out = `${o.dir}/out`;
  const native = `${o.dir}/${FRAME_CAD_NATIVE}`;
  return [
    ...bodyArtifacts(
      {
        name: o.name,
        generator: HARDWARE_CAD_GENERATOR,
        tool,
        generatorNote: `Generated by ${HARDWARE_CAD_GENERATOR} from ${native}/params.json (protoboard run cad:generate, then cad:export; or hardware-cad).`,
      },
      { step: `${out}/body.step`, glb: `${out}/body.glb`, manifest: `${out}/body.manifest.json`, iface: (id) => `${out}/interfaces/${id}.glb` },
    ),
    { id: "cad_params", name: `${o.name} generator parameters`, type: "cad", role: "source", format: "json", filePath: `${native}/params.json`, description: "Kind, diameter, length and head or outer size read from this module." },
  ];
}
