const PARSED = {};
for (const [ch, s] of Object.entries(G)) PARSED[ch] = s.split(";").map((pl) => pl.trim().split(" ").map((xy) => xy.split(",").map(Number)));
const BOX = [[[0, 0], [4, 0], [4, 6], [0, 6], [0, 0]]];

/** Polylines (flat [x, y, ...]) for `text` centered at (x, y), cap height `size` mm, rotated by `a` radians (canvas sense). */
export function strokeText(text, x, y, size, a = 0, mirror = false) {
  const u = size / 6;
  const adv = 5.6;
  const chars = [...String(text).toUpperCase()];
  const width = chars.length * adv - 1.6;
  const ox = -width / 2, oy = -3;
  const c = Math.cos(a), s = Math.sin(a);
  const out = [];
  chars.forEach((ch, i) => {
    if (ch === " ") return;
    const glyph = PARSED[ch] ?? BOX;
    for (const pl of glyph) {
      const flat = [];
      for (const [gx, gy] of pl) {
        let lx = (ox + i * adv + gx) * u, ly = (oy + gy) * u;
        if (mirror) lx = -lx;
        flat.push(x + lx * c - ly * s, y + lx * s + ly * c);
      }
      out.push(flat);
    }
  });
  return out;
}
