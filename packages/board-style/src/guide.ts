/**
 * STYLE.md: the agent-facing guide, written from the resolved style, the decisions log, the examples and the asset
 * registry. It is generated (never edited by hand): the procedure, every token by class with its value, where the
 * value came from and its guard rail, the rules decisions added, and what to look at.
 */
import { mkdirSync, renameSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { canonical } from "@protoboardai/board";
import { loadAssets } from "./assets.js";
import { listDecisions, type ListedDecision } from "./decisions.js";
import { exampleDirs, searchExamples, type ExampleHit } from "./examples.js";
import type { ResolvedStyle } from "./resolve.js";
import { formatValue, TOKEN_CLASSES, TOKENS } from "./tokens.js";

const CLASS_TITLE = { fab: "Fab tokens (guarded by the fab profile)", electrical: "Electrical tokens (never changed for looks)", placement: "Placement tokens (only when asked, before routing)", cosmetic: "Cosmetic tokens" } as const;

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

/** The text of STYLE.md for a resolved style. */
export function styleGuide(style: ResolvedStyle, o: { decisions?: ListedDecision[]; examples?: ExampleHit[] } = {}): string {
  const decisions = o.decisions ?? safe(() => listDecisions(style.places), []);
  const examples = o.examples ?? safe(() => searchExamples(exampleDirs(style.theme.id, style.places)), []);
  const L: string[] = [];
  L.push(`# Board style: ${style.theme.name}`, "");
  L.push("Generated by `@protoboardai/board-style` from the resolved theme, the decisions log, the examples and the asset registry. Do not edit by hand: change a token (in your layer) or record a decision, then regenerate.", "");
  L.push(`Theme chain: ${style.theme.chain.join(" > ")}. Layers: ${style.layers.map((l) => `${l.name}${l.present ? "" : " (none)"}`).join(", ")}. Fab profile: ${style.fab.name}.`, "");
  L.push("## How to use this style", "");
  L.push(
    "1. Read at layout start: this guide, the decisions below, and the example captions (open the images when a caption is relevant). Fab tokens feed design rules and quoting before placement.",
    "2. Placement: keep each group together. Align parts to the grid or to frames only when the user asks (`alignParts`), before routing; a move that lengthens a critical net past the limit is reported, not made.",
    "3. Routing: copper follows the electrical tokens; no cosmetic token overrides a net class.",
    "4. Silkscreen last, with the tools in order: `styleFrames`, `styleHazard`, `styleNameplate`, `styleEdgeText`, `styleMarks`, `styleDesignators`. Each returns a change set; propose it, and the person accepts it. Re-running a tool updates what it made before.",
    "5. Check with `checkStyle`: drift warnings never block; fab guard errors are real fab limits. Render top and bottom with `renderAsBuilt` and look at them before asking.",
    "6. Learn: when the user says \"I'd rather it look like this\", restate it as token changes, call `applyCorrection` (it renders before and after), ask the scope (this board, this project, all boards) unless it is obvious, then record the decision. A project change made twice is offered for promotion to the user layer.",
    "",
  );
  L.push("Judgment that stays with you: which keep-outs are hazards and what their tags say, where a personal mark goes, the wording of the motto. Propose, render, ask.", "");
  for (const cls of TOKEN_CLASSES) {
    L.push(`## ${CLASS_TITLE[cls]}`, "");
    L.push("| Token | Value | Set by | Guard rail or note |", "|---|---|---|---|");
    for (const def of TOKENS.filter((t) => t.class === cls)) {
      const t = style.tokens[def.path];
      const value = formatValue(def, t.value) + (t.clamp ? ` (effective ${formatValue(def, t.effective)})` : "");
      const by = t.layer === "shipped" ? `theme ${t.theme}` : t.layer === "default" ? "default" : `${t.layer}${t.decision ? `, ${t.decision}` : ""}`;
      const note = [def.guard, def.specifiedOnly ? "specified only: no tool acts on it yet" : "", t.clamp?.reason].filter(Boolean).join("; ");
      L.push(`| \`${def.path}\` | ${cell(value)} | ${cell(by)} | ${cell(note || def.description)} |`);
    }
    L.push("");
  }
  const live = style.guards.filter((g) => g.severity !== "info");
  L.push("## Guard rails now", "");
  if (!live.length) L.push("No fab or electrical guard rail is tripped.");
  for (const g of style.guards) L.push(`- ${g.severity}: ${g.message} (\`${g.token}\`)`);
  L.push("");
  L.push("## Decisions", "");
  const rules = decisions.filter((d) => d.effective === "accepted" && d.rule);
  if (rules.length) {
    L.push("Rules that are not tokens:", "");
    for (const d of rules) L.push(`- ${d.rule} (${d.id}, ${d.scope})`);
    L.push("");
  }
  if (!decisions.length) L.push("No decisions recorded yet.");
  for (const d of [...decisions].reverse()) L.push(`- ${d.id} (${d.scope}${d.board ? ` ${d.board}` : ""}, ${d.date}, ${d.effective}): "${d.said}"${d.tokens.length ? `: ${d.tokens.map((t) => `\`${t.path}\` to ${canonical(t.to)}`).join(", ")}` : ""}`);
  L.push("");
  L.push("## Examples", "");
  if (!examples.length) L.push("No examples in the theme, user or project folders.");
  for (const e of examples) L.push(`- ${e.layer}: \`${e.file}\`: ${e.title || "(untitled)"}${e.tags.length ? ` [${e.tags.join(", ")}]` : ""}${e.copy ? `. Copy: ${e.copy}` : ""}${e.avoid ? `. Avoid: ${e.avoid}` : ""}`);
  L.push("");
  L.push("## Marks and assets", "");
  const assets = safe(() => [...loadAssets(style.places).values()], []);
  for (const a of assets) L.push(`- \`${a.entry.id}\` (${a.layer}, ${a.entry.kind}): ${a.entry.status}${a.entry.traced ? ", traced from an image" : ""}; license ${a.entry.license}; ${a.verified ? "hash verified" : "HASH MISMATCH"}; ${a.entry.source}`);
  L.push("");
  return L.join("\n");
}

function safe<T>(f: () => T, fallback: T): T {
  try {
    return f();
  } catch {
    return fallback;
  }
}

/** Write STYLE.md (default: the project's style folder). */
export function writeStyleGuide(style: ResolvedStyle, file?: string): string {
  const target = file ?? style.places.project?.guide;
  if (!target) throw new Error("no project style folder to write STYLE.md into: give a file");
  mkdirSync(dirname(target), { recursive: true });
  const tmp = `${target}.tmp-${process.pid}`;
  writeFileSync(tmp, styleGuide(style));
  renameSync(tmp, target);
  return target;
}
