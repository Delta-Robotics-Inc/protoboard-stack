#!/usr/bin/env node
/**
 * The generated reference documents (PB-809):
 *
 *   docs/reference/cli.md         from `protoboard --help`
 *   docs/reference/extensions.md  from every packages/<pkg>/protoboard-extension.json,
 *                                 its skills and its eval cases
 *
 *   node scripts/reference-docs.mjs            write both
 *   node scripts/reference-docs.mjs --check    exit 1 when either is out of date
 *
 * packages/cli/test/reference-docs.test.ts runs the same comparison in `npm test`,
 * so a command, flag, operation or skill that changes without the reference
 * failing the tests cannot happen.
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CLI = join(REPO, "packages/cli/bin/protoboard.mjs");

export const REFERENCE_FILES = {
  "docs/reference/cli.md": () => cliReference(),
  "docs/reference/extensions.md": () => extensionsReference(),
};

const HEADER = (source) =>
  `<!-- Generated by scripts/reference-docs.mjs from ${source}. Do not edit by hand: run \`node scripts/reference-docs.mjs\`. packages/cli/test/reference-docs.test.ts fails when this file is out of date. -->\n`;

/** Escape text for a Markdown table cell. */
const cell = (s) => s.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
/** Inline code that may sit in a table cell. */
const code = (s) => "`" + s.replace(/\|/g, "\\|") + "`";

// ---------------------------------------------------------------------------
// CLI

export function helpText() {
  const r = spawnSync(process.execPath, [CLI, "--help"], { encoding: "utf8", cwd: REPO });
  if (r.status !== 0) throw new Error(`protoboard --help failed: ${r.stderr}`);
  return r.stdout;
}

/** The help's Commands or Options block as entries: the signature and its description lines. */
export function helpEntries(help, section, next) {
  const start = help.indexOf(`\n  ${section}\n`);
  const end = next ? help.indexOf(`\n  ${next}\n`) : help.length;
  if (start < 0 || end < 0) throw new Error(`no "${section}" section in the help`);
  const entries = [];
  for (const line of help.slice(start + section.length + 4, end).split("\n")) {
    if (!line.trim()) continue;
    const m = /^ {4}(\S.*?)(?: {2,}(\S.*))?$/.exec(line);
    if (m) entries.push({ signature: m[1].trim(), text: m[2] ? [m[2].trim()] : [] });
    else if (entries.length) entries[entries.length - 1].text.push(line.trim());
  }
  return entries.map((e) => ({ signature: e.signature, description: e.text.join(" ") }));
}

export function cliReference() {
  const help = helpText();
  const commands = helpEntries(help, "Commands", "Options");
  const options = helpEntries(help, "Options");
  const lines = [
    HEADER("`protoboard --help`"),
    "# CLI reference",
    "",
    "`protoboard` (alias `pb`) is the command-line interface of the Protoboard Stack, in `@protoboardai/cli`.",
    "Every command takes `--format json` for machine output and `--cwd <dir>` for the project",
    "directory (default: the current one, or the nearest folder above it with a `protoboard.config.ts`).",
    "`protoboard --version` prints the CLI's version, and with `--json` where the build came from (commit,",
    "uncommitted changes, branch, and whether it is a release); `protoboard <command> --help` prints this help",
    "without running the command.",
    "",
    "The [quickstart](../quickstart.md) walks through these commands in order;",
    "[configuration](configuration.md) covers the files and environment variables they read.",
    "",
    "## Commands",
    "",
    "| Command | What it does |",
    "| --- | --- |",
    ...commands.map((c) => `| ${code(c.signature)} | ${cell(c.description)} |`),
    "",
    "## Options",
    "",
    "Options prefixed with a command name (`dev:`, `evals:`) apply to that command only.",
    "",
    "| Option | Meaning |",
    "| --- | --- |",
    ...options.map((o) => `| ${code(o.signature)} | ${cell(o.description)} |`),
    "",
    "## The help text",
    "",
    "```text",
    help.replace(/\s+$/, ""),
    "```",
    "",
  ];
  return lines.join("\n");
}

// ---------------------------------------------------------------------------
// Extensions, skills, eval cases

export function extensionManifests() {
  const dir = join(REPO, "packages");
  return readdirSync(dir)
    .filter((p) => existsSync(join(dir, p, "protoboard-extension.json")))
    .map((p) => ({ folder: `packages/${p}`, manifest: JSON.parse(readFileSync(join(dir, p, "protoboard-extension.json"), "utf8")) }))
    .sort((a, b) => a.manifest.id.localeCompare(b.manifest.id));
}

function evalCases(folder) {
  const dir = join(REPO, folder, "evals");
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((c) => existsSync(join(dir, c, "case.json")))
    .sort()
    .map((c) => {
      const k = JSON.parse(readFileSync(join(dir, c, "case.json"), "utf8"));
      return { id: c, title: k.title ?? "", skills: k.skills ?? [] };
    });
}

const opRow = (o) => `| ${code(o.id)} | ${o.effect ?? "pure"} | ${o.requires?.length ? o.requires.map(code).join(", ") : "—"} | ${cell(o.summary ?? "")} |`;

export function extensionsReference() {
  const exts = extensionManifests();
  const skills = exts.flatMap(({ folder, manifest }) => (manifest.skills ?? []).map((s) => ({ ...s, ext: manifest.id, folder })));
  const caps = exts.flatMap(({ manifest }) => (manifest.capabilities ?? []).map((c) => ({ ...c, ext: manifest.id })));
  const lines = [
    HEADER("the extensions' `protoboard-extension.json`, skills and eval cases"),
    "# Extensions and skills",
    "",
    `The ${exts.length} first-party extensions in this repository, what each provides, and every skill`,
    "they ship. A project uses an extension by installing its package and listing it in",
    "`extensions` in `protoboard.config.ts`; a capability provider is also loaded when a module's",
    "`<capability>.config.ts` names it. In a project, `protoboard doctor` lists what is configured,",
    "`protoboard skills` the skills, `protoboard capabilities` the providers, and `protoboard evals --list`",
    "the eval cases. Writing a provider: [the provider guide](../guides/writing-a-capability-provider.md).",
    "",
    "## Capability providers",
    "",
    "| Capability | Provider | Native folder | Summary |",
    "| --- | --- | --- | --- |",
    ...caps
      .sort((a, b) => a.id.localeCompare(b.id) || a.ext.localeCompare(b.ext))
      .map((c) => `| ${code(c.id)} | ${code(c.ext)} | ${code((c.native ?? c.ext.replace(/^@[^/]+\//, "").replace(/^ext-/, "")) + "/")} | ${cell(c.summary ?? "")} |`),
    "",
    "## Skills",
    "",
    "Start with **build-a-project**: it takes an agent from a brief to a release and delegates to the others.",
    "`protoboard skills export --host all` puts them where an agent finds them (`claude-code`: `.claude/skills/`; `agents-md`: a list in `AGENTS.md`); a project made by `protoboard init` runs it at the end of `npm install`.",
    "",
    "| Skill | Extension | Verified by | Summary |",
    "| --- | --- | --- | --- |",
    ...skills.map(
      (s) =>
        `| ${s.package ? code(s.id) + ` (from ${code(s.package)})` : `[${code(s.id)}](../../${s.folder}/${s.path})`} | ${code(s.ext)} | ${s.verifiedBy ? code(s.verifiedBy) : "—"} | ${cell(s.summary ?? "")} |`,
    ),
    "",
    "## Extensions",
    "",
  ];
  for (const { folder, manifest: m } of exts) {
    const cases = evalCases(folder);
    lines.push(`### ${m.id}`, "", `${cell(m.description ?? "")} Version ${m.version}; source [${folder}](../../${folder}).`, "");
    const compat = Object.entries(m.compatibility ?? {}).map(([k, v]) => `${k} ${v}`);
    if (compat.length) lines.push(`Compatibility: ${compat.map(code).join(", ")}.`, "");
    if (m.capabilities?.length) {
      for (const c of m.capabilities) {
        const constraints = Object.entries(c.constraints ?? {});
        lines.push(
          `**Capability ${code(c.id)}**: ${cell(c.summary ?? "")}. Operations ${Object.keys(c.operations ?? {}).map((o) => code(`${c.id}:${o}`)).join(", ")}.${constraints.length ? ` Constraints: ${constraints.map(([k, v]) => `${code(k)}${v.required ? " (required)" : ""}`).join(", ")}.` : ""}`,
          "",
        );
      }
    }
    if (m.operations?.length) lines.push("| Operation | Effect | Needs | Summary |", "| --- | --- | --- | --- |", ...m.operations.map(opRow), "");
    if (m.checks?.length) lines.push("| Check | Summary |", "| --- | --- |", ...m.checks.map((c) => `| ${code(c.id)} | ${cell(c.summary ?? "")} |`), "");
    if (m.tools?.length)
      lines.push(
        "| Tool | Purpose | Runtime |",
        "| --- | --- | --- |",
        ...m.tools.map((t) => `| ${code(t.id)} | ${cell(t.purpose ?? "")} | ${t.runtime ? `${code(t.runtime.id)} (${t.runtime.kind}): ${t.runtime.packages.map(code).join(" ")}` : "—"} |`),
        "",
      );
    if (m.skills?.length) lines.push(`Skills: ${m.skills.map((s) => code(s.id)).join(", ")}.`, "");
    if (cases.length) lines.push(`Eval cases: ${cases.map((c) => `${code(c.id)} (${cell(c.title)})`).join("; ")}.`, "");
  }
  return lines.join("\n").replace(/\n+$/, "\n");
}

// ---------------------------------------------------------------------------

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [rel, make] of Object.entries(REFERENCE_FILES)) {
    const file = join(REPO, rel);
    const want = make();
    const have = existsSync(file) ? readFileSync(file, "utf8") : undefined;
    if (have === want) continue;
    if (check) {
      console.error(`${rel} is out of date: run node scripts/reference-docs.mjs`);
      stale++;
    } else {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, want);
      console.log(`wrote ${rel}`);
    }
  }
  process.exitCode = stale ? 1 : 0;
}
